// stripRegisteredProjectBlocks: project CLAUDE.md / AGENTS.md + rules
// ---------------------------------------------------------------------------

describe('stripRegisteredProjectBlocks', () => {
  let home;
  let cwd;
  let proj;

  before(() => {
    home = mkdtempSync(join(tmpdir(), 'ijfw-rhome-'));
    cwd = mkdtempSync(join(tmpdir(), 'ijfw-rcwd-'));
    proj = mkdtempSync(join(tmpdir(), 'ijfw-proj-'));

    // Registry points at the fake project.
    write(join(home, '.ijfw', 'registry.md'), [
      `${proj} | abc123 | 2026-06-08T00:00:00Z`,
      '/does/not/exist | dead | 2026-06-08T00:00:01Z',
      '',
    ].join('\n'));

    // Polluted project CLAUDE.md (user content + IJFW region).
    write(join(proj, 'CLAUDE.md'), [
      '# Project Context',
      'Stack: my own stack',
      '',
      '<!-- IJFW-MEMORY-START (managed -- do not edit manually) -->',
      '<ijfw-memory>',
      'injected',
      '</ijfw-memory>',
      '<ijfw-routing>',
      'route',
      '</ijfw-routing>',
      '<!-- IJFW-MEMORY-END -->',
      '',
      'My tail content.',
      '',
    ].join('\n'));

    // Polluted project AGENTS.md.
    write(join(proj, 'AGENTS.md'), [
      '# Agents',
      'user line',
      '<!-- IJFW-AGENTS-START -->',
      'agents block',
      '<!-- IJFW-AGENTS-END -->',
      '',
    ].join('\n'));

    // cwd rules files.
    write(join(cwd, '.cursor', 'rules', 'ijfw.mdc'), 'wholly ijfw\n');
    write(join(cwd, '.windsurfrules'), [
      'user windsurf prefs',
      '<!-- IJFW-ROUTING-START -->',
      'r',
      '<!-- IJFW-ROUTING-END -->',
      '',
    ].join('\n'));
    // Copilot file that is WHOLLY an IJFW region -> becomes empty -> deleted.
    write(join(cwd, '.github', 'copilot-instructions.md'), [
      '<!-- IJFW-MEMORY-START -->',
      'only ijfw',
      '<!-- IJFW-MEMORY-END -->',
      '',
    ].join('\n'));
  });

  after(() => {
    rmSync(home, { recursive: true, force: true });
    rmSync(cwd, { recursive: true, force: true });
    rmSync(proj, { recursive: true, force: true });
  });

  it('strips project blocks, preserves user content, handles rules files, backs up', () => {
    const results = stripRegisteredProjectBlocks({
      home, cwd, registryPath: join(home, '.ijfw', 'registry.md'),
    });

    // Project CLAUDE.md — region gone, user content intact.
    const claude = readFileSync(join(proj, 'CLAUDE.md'), 'utf8');
    assert.ok(claude.includes('# Project Context'));
    assert.ok(claude.includes('Stack: my own stack'));
    assert.ok(claude.includes('My tail content.'));
    assert.ok(!claude.includes('IJFW-MEMORY'));
    assert.ok(!claude.includes('ijfw-memory'));
    assert.ok(!claude.includes('ijfw-routing'));

    // Project AGENTS.md.
    const agents = readFileSync(join(proj, 'AGENTS.md'), 'utf8');
    assert.ok(agents.includes('# Agents'));
    assert.ok(agents.includes('user line'));
    assert.ok(!agents.includes('IJFW-AGENTS'));

    // cwd: cursor rule deleted wholesale.
    assert.ok(!existsSync(join(cwd, '.cursor', 'rules', 'ijfw.mdc')), 'cursor rule deleted');

    // cwd: windsurf rules region stripped, user prefs kept (file survives).
    const ws = readFileSync(join(cwd, '.windsurfrules'), 'utf8');
    assert.ok(ws.includes('user windsurf prefs'));
    assert.ok(!ws.includes('IJFW-ROUTING'));

    // cwd: copilot file was wholly IJFW -> deleted (became empty).
    assert.ok(!existsSync(join(cwd, '.github', 'copilot-instructions.md')), 'empty copilot file deleted');

    // Backups created for files we rewrote.
    assert.ok(hasBackup(join(proj, 'CLAUDE.md')), 'CLAUDE.md backup');
    assert.ok(hasBackup(join(proj, 'AGENTS.md')), 'AGENTS.md backup');

    // Summary is non-empty and human-readable.
    assert.ok(results.length >= 5);
  });

  it('returns [] when registry is missing (no-op)', () => {
    const h2 = mkdtempSync(join(tmpdir(), 'ijfw-noreg-'));
    const c2 = mkdtempSync(join(tmpdir(), 'ijfw-noregcwd-'));
    try {
      const results = stripRegisteredProjectBlocks({
        home: h2, cwd: c2, registryPath: join(h2, '.ijfw', 'registry.md'),
      });
      assert.deepEqual(results, []);
    } finally {
      rmSync(h2, { recursive: true, force: true });
      rmSync(c2, { recursive: true, force: true });
    }
  });
});

