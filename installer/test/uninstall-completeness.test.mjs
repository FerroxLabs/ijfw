// P3 "honest uninstall" completeness tests.
//
// Verifies that cleanPlatforms() removes the IJFW MCP entry from ALL 15
// platforms (with focus on the 8 previously-missing ones) and that
// stripRegisteredProjectBlocks() strips IJFW marker regions from registered
// project CLAUDE.md / AGENTS.md + cwd rules files while preserving every
// user-authored line and creating backups.
//
// Style (a): import the exported functions and drive them against a scratch
// sandbox (injected home/cwd/registryPath). No subprocess -> deterministic, no
// spawn flake, and the real $HOME is never touched.
//
// Run: node --test test/uninstall-completeness.test.mjs

import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import {
  mkdtempSync, rmSync, mkdirSync, writeFileSync, readFileSync, existsSync,
  readdirSync, copyFileSync,
} from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  stripIjfwRegions,
  cleanPlatforms,
  stripRegisteredProjectBlocks,
  parseRegistryPaths,
  resolveAiderTemplate,
  removeAiderFileIfPristine,
} from '../src/uninstall.js';

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT = resolve(dirname(__filename), '..', '..');

function write(p, content) {
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
}

function hasBackup(p) {
  // A `<file>.bak.<TS>` sibling exists.
  const dir = dirname(p);
  const base = p.split('/').pop();
  if (!existsSync(dir)) return false;
  return readdirSync(dir).some((n) => n.startsWith(base + '.bak.'));
}

// ---------------------------------------------------------------------------
// stripIjfwRegions: pure region surgery
// ---------------------------------------------------------------------------

describe('stripIjfwRegions (pure)', () => {
  it('strips CLAUDE.md MEMORY region (parenthetical start tag) and keeps user content', () => {
    const src = [
      '# My Project',
      '',
      'My own notes here.',
      '',
      '<!-- IJFW-MEMORY-START (managed -- do not edit manually) -->',
      '<ijfw-memory>',
      'project memory blah',
      '</ijfw-memory>',
      '<!-- IJFW-MEMORY-END -->',
      '',
      'More of my notes.',
      '',
    ].join('\n');
    const { text, changed } = stripIjfwRegions(src);
    assert.equal(changed, true);
    assert.ok(text.includes('# My Project'));
    assert.ok(text.includes('My own notes here.'));
    assert.ok(text.includes('More of my notes.'));
    assert.ok(!text.includes('IJFW-MEMORY-START'));
    assert.ok(!text.includes('IJFW-MEMORY-END'));
    assert.ok(!text.includes('ijfw-memory'));
  });

  it('strips bare AGENTS.md regions + explainer (Four/Five count word) + autogen comment', () => {
    const src = [
      '# AGENTS',
      'Five IJFW-managed regions live in this file. Content outside the markers is',
      'yours -- IJFW will never touch it.',
      '',
      '<!-- IJFW-MEMORY-START -->',
      'x',
      '<!-- IJFW-MEMORY-END -->',
      '',
      '<!-- IJFW-ROUTING-START -->',
      'y',
      '<!-- IJFW-ROUTING-END -->',
      '<!-- Auto-generated by IJFW from repo scan. Edit freely. -->',
      'user tail',
      '',
    ].join('\n');
    const { text, changed } = stripIjfwRegions(src);
    assert.equal(changed, true);
    assert.ok(text.includes('# AGENTS'));
    assert.ok(text.includes('user tail'));
    assert.ok(!text.includes('IJFW-managed regions'));
    assert.ok(!text.includes('Auto-generated by IJFW'));
    assert.ok(!text.includes('IJFW-ROUTING'));
  });

  it('is a no-op (changed=false) on text with no IJFW markers', () => {
    const src = '# Plain\n\nNothing to see.\n';
    const { text, changed } = stripIjfwRegions(src);
    assert.equal(changed, false);
    assert.equal(text, src);
  });
});

