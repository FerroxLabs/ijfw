/**
 * test-truncation-recovery.js — v1.5.0 T20: G1 truncation recovery proof.
 *
 * For every fixture in `mcp-server/fixtures/truncation-corpus/`:
 *   1. Materialise a fresh temp project from the fixture's pre-recorded
 *      event log + intent journal + snapshot sidecars + on-disk target
 *      content (the "moment of truncation" state).
 *   2. Run `detectTruncation` against the fixture's events + journal.
 *   3. Run `recoverSubagent` (which calls `query('state.replay', ...)`).
 *   4. Compare every target file's post-recovery content against
 *      `meta.json`'s `expectedFinalState`.
 *
 * The "measured rate" is the fraction of fixtures whose post-recovery
 * state does NOT match the expected final state — i.e. the truncation
 * rate that SURVIVES recovery. The brief requires that this rate ≤ 31%
 * (halves the 62% v1.4.x baseline).
 *
 * Real fs + real `query()` — no mocks. Determinism: every fixture is
 * regenerated by `_generate-corpus.js` and committed to the repo; the
 * test reconstructs identical projects from identical inputs.
 *
 * Run: `node --test test-truncation-recovery.js`
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  cpSync, existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync,
  rmSync, writeFileSync, statSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  detectTruncation,
  recoverSubagent,
  measureTruncationRate,
  writeRateArtifact,
  listFixtures,
  TRUNCATION_RATE_THRESHOLD,
  TRUNCATION_BASELINE_RATE,
} from './src/recovery/truncation.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CORPUS_DIR = join(__dirname, 'fixtures', 'truncation-corpus');

// ----- Helpers ----------------------------------------------------------

function mkTempProject() {
  return mkdtempSync(join(tmpdir(), 't20-trunc-'));
}

/**
 * Materialise a fixture into a temp project:
 *   - `intent-journal.jsonl` and snapshot sidecars (with absPath rewritten
 *     to point INTO the temp project) go under `.ijfw/state/`.
 *   - Per-subagent event log (events.jsonl) goes under
 *     `.ijfw/wave-<waveId>/events-<subId>.jsonl`.
 *   - Target files are copied from `target/` preserving relative layout.
 */
function materialise(fixture, projectRoot) {
  const { id, dir, meta } = fixture;
  const { waveId, subId } = meta;

  // Intent journal.
  const journalSrc = join(dir, 'intent-journal.jsonl');
  if (existsSync(journalSrc)) {
    const journalDst = join(projectRoot, '.ijfw', 'state', 'intent-journal.jsonl');
    mkdirSync(dirname(journalDst), { recursive: true });
    cpSync(journalSrc, journalDst);
  }

  // Snapshot sidecars — patch <<ABS>> placeholders to real absolute paths.
  const snapSrcDir = join(dir, 'snapshots');
  if (existsSync(snapSrcDir)) {
    const snapDstDir = join(projectRoot, '.ijfw', 'state', 'intent-snapshots');
    mkdirSync(snapDstDir, { recursive: true });
    for (const name of readdirSync(snapSrcDir)) {
      const src = join(snapSrcDir, name);
      const raw = readFileSync(src, 'utf8');
      const parsed = JSON.parse(raw);
      for (const t of parsed.targets || []) {
        if (t.absPath === '<<ABS>>') t.absPath = join(projectRoot, t.relPath);
      }
      writeFileSync(join(snapDstDir, name), JSON.stringify(parsed));
    }
  }

  // Per-subagent event log.
  const eventsSrc = join(dir, 'events.jsonl');
  if (existsSync(eventsSrc)) {
    const evDst = join(projectRoot, '.ijfw', `wave-${waveId}`, `events-${subId}.jsonl`);
    mkdirSync(dirname(evDst), { recursive: true });
    cpSync(eventsSrc, evDst);
  }

  // Target files — copy preserving relative layout.
  const tgtSrcDir = join(dir, 'target');
  if (existsSync(tgtSrcDir)) {
    // Manual recursive walk: node 22's cpSync({recursive:true}) silently
    // skips files when the destination subdir already exists (which it does
    // here — the journal/events writes above created projectRoot/.ijfw/...
    // ahead of this merge). Node 25 merges correctly. Walk file-by-file so
    // the test is identical on every node version + OS.
    copyTreeMerging(tgtSrcDir, projectRoot);
  }

  return { fixtureId: id, projectRoot };
}

function copyTreeMerging(srcDir, dstDir) {
  for (const entry of readdirSync(srcDir, { withFileTypes: true })) {
    const src = join(srcDir, entry.name);
    const dst = join(dstDir, entry.name);
    if (entry.isDirectory()) {
      mkdirSync(dst, { recursive: true });
      copyTreeMerging(src, dst);
    } else if (entry.isFile()) {
      mkdirSync(dirname(dst), { recursive: true });
      cpSync(src, dst, { force: true });
    }
  }
}

function readJsonlFile(absPath) {
  if (!existsSync(absPath)) return [];
  const out = [];
  for (const line of readFileSync(absPath, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t) continue;
    try { out.push(JSON.parse(t)); } catch { /* skip */ }
  }
  return out;
}

function readMaybe(absPath) {
  if (!existsSync(absPath)) return null;
  return readFileSync(absPath, 'utf8');
}

/**
 * Runs one fixture end-to-end. Returns the shape `measureTruncationRate`
 * expects + per-fixture diagnostics for the test's detailed assertions.
 */
async function runFixture(fixture) {
  const root = mkTempProject();
  try {
    materialise(fixture, root);
    const { meta } = fixture;
    const journal = readJsonlFile(join(root, '.ijfw', 'state', 'intent-journal.jsonl'));
    const events = readJsonlFile(
      join(root, '.ijfw', `wave-${meta.waveId}`, `events-${meta.subId}.jsonl`),
    );

    const detection = detectTruncation({
      events, journal,
      expectedTerminalVerb: meta.expectedTerminalVerb,
    });

    const recovery = await recoverSubagent({
      projectRoot: root, waveId: meta.waveId, subId: meta.subId,
    });

    // Post-recovery state check.
    let allMatch = true;
    const stateDiffs = [];
    for (const [rel, expected] of Object.entries(meta.expectedFinalState || {})) {
      const abs = join(root, rel);
      const actual = readMaybe(abs);
      if (expected === null) {
        // expected-deleted
        if (actual !== null) {
          allMatch = false;
          stateDiffs.push({ rel, expected: '(deleted)', actual: actual.slice(0, 120) });
        }
      } else if (actual !== expected) {
        allMatch = false;
        stateDiffs.push({
          rel,
          expected: expected.slice(0, 120),
          actual: actual === null ? '(missing)' : actual.slice(0, 120),
        });
      }
    }

    return {
      truncated: detection.truncated,
      recovered: recovery.recovered,
      expectedFinalStateMatches: allMatch,
      category: meta.category,
      detection,
      recovery,
      stateDiffs,
      _root: root,
    };
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

// ----- Sanity: corpus is present ----------------------------------------

test('corpus: 25 fixtures across 5 categories', () => {
  assert.equal(existsSync(CORPUS_DIR), true, `corpus dir at ${CORPUS_DIR}`);
  const fixtures = listFixtures(CORPUS_DIR);
  assert.equal(fixtures.length, 25, `expected 25 fixtures, got ${fixtures.length}`);
  const byCat = {};
  for (const f of fixtures) {
    byCat[f.meta.category] = (byCat[f.meta.category] || 0) + 1;
  }
  assert.deepEqual(
    byCat,
    {
      'clean-exit': 5,
      'mid-overwrite': 5,
      'mid-append': 5,
      'no-events': 5,
      'error-terminated': 5,
    },
    'each category has 5 fixtures',
  );
});

// ----- Per-fixture: detection + recovery + final-state -------------------

test('per-fixture: detection classifies + recovery restores expected state', async () => {
  const fixtures = listFixtures(CORPUS_DIR);
  for (const fx of fixtures) {
    const r = await runFixture(fx);
    // Detection: the category matches the expected detection family.
    if (fx.meta.expectedDetection?.truncated === false) {
      assert.equal(
        r.truncated, false,
        `${fx.id}: expected clean detection, got ${JSON.stringify(r.detection)}`,
      );
    } else {
      assert.notEqual(
        r.truncated, false,
        `${fx.id}: expected truncation detected, got clean detection`,
      );
      const expCode = fx.meta.expectedDetection?.truncated;
      if (expCode) {
        assert.equal(
          r.truncated, expCode,
          `${fx.id}: expected truncation code '${expCode}', got '${r.truncated}'`,
        );
      }
    }

    // Recovery: ok===true for every fixture.
    assert.equal(
      r.recovered, true,
      `${fx.id}: replay did not return ok (${JSON.stringify(r.recovery)})`,
    );

    // Final state: every expected file matches.
    assert.equal(
      r.expectedFinalStateMatches, true,
      `${fx.id}: post-recovery state diverges from expectedFinalState — ${
        JSON.stringify(r.stateDiffs)}`,
    );
  }
});

// ----- Aggregate measurement: rate ≤ 31% --------------------------------

test('measured truncation rate over corpus is ≤ 31% (halves 62% baseline)', async () => {
  const fixtures = listFixtures(CORPUS_DIR);
  const result = await measureTruncationRate({
    fixtures,
    runOne: async (fx) => runFixture(fx),
  });
  assert.equal(result.corpusSize, 25, 'corpus size 25');
  assert.equal(result.baselineRate, TRUNCATION_BASELINE_RATE, 'baseline rate published');
  assert.equal(result.threshold, TRUNCATION_RATE_THRESHOLD, 'threshold published');
  assert.ok(
    result.ratePostRecovery <= TRUNCATION_RATE_THRESHOLD,
    `measured rate ${result.ratePostRecovery} must be ≤ ${TRUNCATION_RATE_THRESHOLD}`,
  );
  assert.equal(result.passed, true, 'result.passed === true');
  assert.equal(result.byCategory.length, 5, '5 category buckets reported');
  // Sanity: 20 truncated fixtures (everything except clean-exit).
  assert.equal(result.truncatedCount, 20, 'truncatedCount = 25 - 5 clean = 20');
  // EVERY fixture recovers successfully (the brief's stretch result).
  assert.equal(result.unrecoveredCount, 0, 'every fixture in corpus recovers');
  assert.equal(result.ratePostRecovery, 0, 'measured rate is 0 (all fixtures recover)');
});

// ----- Artifact: rate published to telemetry dir ------------------------

test('rate artifact: writeRateArtifact emits .ijfw/telemetry/truncation-rate.json', async () => {
  const fixtures = listFixtures(CORPUS_DIR);
  const result = await measureTruncationRate({
    fixtures,
    runOne: async (fx) => runFixture(fx),
  });
  const artifactRoot = mkTempProject();
  try {
    const path = writeRateArtifact(artifactRoot, result);
    assert.equal(
      relative(artifactRoot, path),
      join('.ijfw', 'telemetry', 'truncation-rate.json'),
      'artifact path under .ijfw/telemetry/',
    );
    const persisted = JSON.parse(readFileSync(path, 'utf8'));
    assert.equal(persisted.corpusSize, 25);
    assert.equal(persisted.baselineRate, TRUNCATION_BASELINE_RATE);
    assert.equal(persisted.threshold, TRUNCATION_RATE_THRESHOLD);
    assert.equal(persisted.passed, true);
    assert.ok(Array.isArray(persisted.byCategory), 'byCategory is array');
    assert.ok(Array.isArray(persisted.fixtures), 'per-fixture rows persisted');
    assert.equal(persisted.fixtures.length, 25, '25 fixture rows persisted');
    // Artifact is < 1 MB — sanity check (no runaway payload).
    assert.ok(statSync(path).size < 1024 * 1024, 'artifact under 1 MB');
  } finally {
    rmSync(artifactRoot, { recursive: true, force: true });
  }
});

// ----- Pure-detection contract tests (no fs) -----------------------------

test('detectTruncation: empty input is treated as clean (defensive)', () => {
  const r = detectTruncation({});
  assert.equal(r.truncated, false);
});

test('detectTruncation: error-terminated has top priority', () => {
  const events = [
    { seq: 1, verb: 'workflow.set-phase', verbId: 'v1', outcome: 'ok' },
    { seq: 2, verb: 'wave.advance', verbId: 'v2', outcome: 'error' },
  ];
  const journal = [
    { verb: 'workflow.set-phase', verbId: 'v1', phase: 'begin', kind: 'overwrite' },
    { verb: 'workflow.set-phase', verbId: 'v1', phase: 'commit', kind: 'overwrite' },
    { verb: 'wave.advance', verbId: 'v2', phase: 'begin', kind: 'overwrite' },
  ];
  const r = detectTruncation({ events, journal });
  assert.equal(r.truncated, 'error-terminated');
});

test('detectTruncation: no events + open begin → no-events-open-begin', () => {
  const r = detectTruncation({
    events: [],
    journal: [{ verb: 'workflow.set-phase', verbId: 'v1', phase: 'begin', kind: 'overwrite' }],
  });
  assert.equal(r.truncated, 'no-events-open-begin');
});

test('detectTruncation: clean exit → truncated:false', () => {
  const events = [
    { seq: 1, verb: 'workflow.set-phase', verbId: 'v1', outcome: 'ok' },
    { seq: 2, verb: 'subagent.post-done', verbId: 'v2', outcome: 'ok' },
  ];
  const journal = [
    { verb: 'workflow.set-phase', verbId: 'v1', phase: 'begin', kind: 'overwrite' },
    { verb: 'workflow.set-phase', verbId: 'v1', phase: 'commit', kind: 'overwrite' },
  ];
  const r = detectTruncation({ events, journal });
  assert.equal(r.truncated, false);
});

