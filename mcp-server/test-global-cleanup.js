/**
 * test-global-cleanup.js
 *
 * P0b remediation (v1.6.0 config-write hardening).
 *
 * The P0a cwd guard stops NEW global writes, but installs that already ran the
 * buggy hook carry a stray IJFW block in ~/CLAUDE.md and/or ~/AGENTS.md. This
 * tests claude/hooks/scripts/global-cleanup.sh -- a standalone, idempotent,
 * once-per-machine migration that strips ONLY the IJFW-managed marker regions
 * from those two GLOBAL files, preserving every user-authored line, then drops
 * a sentinel so it never runs again.
 *
 * It must:
 *   - strip all IJFW marker regions from ~/CLAUDE.md and ~/AGENTS.md
 *   - preserve user-authored content verbatim
 *   - back up each file it modifies (.ijfw-cleanup-bak)
 *   - write a sentinel and be a no-op on the second run
 *   - never touch a file that has no IJFW markers (no backup, no edit)
 *   - be wired into session-start.sh
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const REPO_ROOT = path.resolve(__dirname, '..');
const SCRIPTS_DIR = path.join(REPO_ROOT, 'claude', 'hooks', 'scripts');
const CLEANUP_PATH = path.join(SCRIPTS_DIR, 'global-cleanup.sh');
const SESSION_START_PATH = path.join(SCRIPTS_DIR, 'session-start.sh');

const skipOnWin = process.platform === 'win32' ? 'bash not on Windows runner PATH' : undefined;

const POLLUTED_CLAUDE = `# Project Context

Stack: unknown

<!-- Auto-generated by IJFW from repo scan. Edit freely -- IJFW only touches the managed block below. -->

<!-- IJFW-MEMORY-START (managed -- do not edit manually) -->

<ijfw-routing>
IJFW is installed alongside a peer brainstorming skill. Prefer ijfw-workflow.
</ijfw-routing>
<!-- IJFW-MEMORY-END -->

KEEP-ME: my own global note about how I like commits formatted.
`;

const POLLUTED_AGENTS = `KEEP-ME-AGENTS-1: senior engineer rules, line one.
KEEP-ME-AGENTS-2: kills sycophancy, forces verification loops.

Four IJFW-managed regions live in this file. Content outside the markers is
yours -- IJFW will never touch it.

<!-- IJFW-MEMORY-START -->
Project memory at .ijfw/memory/. Call \`ijfw_memory_prelude\` for full context.
<!-- IJFW-MEMORY-END -->

<!-- IJFW-ROUTING-START -->
<!-- IJFW-ROUTING-END -->

<!-- IJFW-AGENTS-START -->
No project agents yet. Run \`ijfw team\` to set them up.
<!-- IJFW-AGENTS-END -->

<!-- IJFW-BLACKBOARD-START -->
<!-- Reserved for Pillar B multi-CLI orchestration. Empty in alpha. -->
<!-- IJFW-BLACKBOARD-END -->
`;

function runCleanup(home, extraEnv = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn('bash', [CLEANUP_PATH], {
      env: {
        PATH: process.env.PATH || '/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin',
        HOME: home,
        ...extraEnv,
      },
      stdio: ['ignore', 'ignore', 'ignore'],
    });
    child.once('exit', (code) => resolve(code));
    child.once('error', reject);
    const t = setTimeout(() => {
      try { child.kill('SIGKILL'); } catch { /* ignore */ }
      reject(new Error('runCleanup: bash exceeded 30s timeout'));
    }, 30000);
    t.unref();
  });
}

async function mkHome() {
  return fs.mkdtemp(path.join(os.tmpdir(), 'ijfw-cleanup-home-'));
}

const IJFW_TOKENS = [
  'IJFW-MEMORY-START', 'IJFW-MEMORY-END',
  'IJFW-ROUTING-START', 'IJFW-AGENTS-START', 'IJFW-BLACKBOARD-START',
  'ijfw-routing', 'ijfw_memory_prelude', 'Four IJFW-managed regions',
];

test('strips IJFW regions from global CLAUDE.md + AGENTS.md, preserves user content', { skip: skipOnWin }, async () => {
  const home = await mkHome();
  await fs.writeFile(path.join(home, 'CLAUDE.md'), POLLUTED_CLAUDE);
  await fs.writeFile(path.join(home, 'AGENTS.md'), POLLUTED_AGENTS);

  const code = await runCleanup(home);
  assert.equal(code, 0, 'global-cleanup.sh should exit 0');

  const claude = await fs.readFile(path.join(home, 'CLAUDE.md'), 'utf8');
  const agents = await fs.readFile(path.join(home, 'AGENTS.md'), 'utf8');

  for (const tok of IJFW_TOKENS) {
    assert.ok(!claude.includes(tok), `~/CLAUDE.md still contains IJFW token "${tok}"`);
    assert.ok(!agents.includes(tok), `~/AGENTS.md still contains IJFW token "${tok}"`);
  }
  // User content survives.
  assert.match(claude, /KEEP-ME: my own global note/, 'user CLAUDE.md content was destroyed');
  assert.match(agents, /KEEP-ME-AGENTS-1: senior engineer rules/, 'user AGENTS.md content was destroyed');
  assert.match(agents, /KEEP-ME-AGENTS-2: kills sycophancy/, 'user AGENTS.md content was destroyed');

  // Backups of the modified files exist.
  assert.ok(existsSync(path.join(home, 'CLAUDE.md.ijfw-cleanup-bak')), 'expected a CLAUDE.md backup');
  assert.ok(existsSync(path.join(home, 'AGENTS.md.ijfw-cleanup-bak')), 'expected an AGENTS.md backup');

  // Sentinel written.
  assert.ok(existsSync(path.join(home, '.ijfw', '.global-cleanup-v1-done')), 'expected a sentinel file');
});

test('idempotent: second run is a no-op (sentinel short-circuits)', { skip: skipOnWin }, async () => {
  const home = await mkHome();
  await fs.writeFile(path.join(home, 'CLAUDE.md'), POLLUTED_CLAUDE);
  await runCleanup(home);
  const afterFirst = await fs.readFile(path.join(home, 'CLAUDE.md'), 'utf8');

  // Re-pollute would normally be re-stripped; sentinel must prevent any action.
  await fs.writeFile(path.join(home, 'CLAUDE.md'), POLLUTED_CLAUDE);
  const code = await runCleanup(home);
  assert.equal(code, 0);
  const afterSecond = await fs.readFile(path.join(home, 'CLAUDE.md'), 'utf8');
  assert.ok(
    afterSecond.includes('IJFW-MEMORY-START'),
    'second run must NOT strip (sentinel should have short-circuited it)',
  );
  // First run did strip.
  assert.ok(!afterFirst.includes('IJFW-MEMORY-START'));
});

test('clean home (no IJFW markers) is untouched, no backup created', { skip: skipOnWin }, async () => {
  const home = await mkHome();
  const pristine = '# My personal global rules\n\nAlways use TypeScript.\n';
  await fs.writeFile(path.join(home, 'CLAUDE.md'), pristine);

  const code = await runCleanup(home);
  assert.equal(code, 0);

  const after = await fs.readFile(path.join(home, 'CLAUDE.md'), 'utf8');
  assert.equal(after, pristine, 'a CLAUDE.md with no IJFW markers must be byte-identical after cleanup');
  assert.ok(!existsSync(path.join(home, 'CLAUDE.md.ijfw-cleanup-bak')), 'must not back up a file it did not modify');
  assert.ok(existsSync(path.join(home, '.ijfw', '.global-cleanup-v1-done')), 'sentinel still written so we do not re-scan every session');
});

test('wired: session-start.sh invokes global-cleanup.sh', async () => {
  const src = await fs.readFile(SESSION_START_PATH, 'utf8');
  assert.match(src, /global-cleanup\.sh/, 'session-start.sh must invoke global-cleanup.sh');
});
